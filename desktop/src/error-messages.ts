export function extractErrorCode(error: unknown): string {
  if (typeof error === 'string') return error;
  if (error instanceof Error) return error.message;
  return '';
}

export function explain(error: unknown): string {
  const code = extractErrorCode(error);
  if (code && code in errorMessages) return errorMessages[code]!;
  const text = code || String(error);
  return errorMessages[text] ?? text;
}

export function explainSafe(error: unknown, fallback: string): string {
  const code = extractErrorCode(error);
  return (code && errorMessages[code]) || fallback;
}
